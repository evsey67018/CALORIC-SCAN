def main():
    with open(os.path.join(os.path.dirname(__file__), "foodseg103_id2label.json"), encoding="utf-8") as fh:
        id2label = json.load(fh)
    items = [None]
    missing = []
    for idx in range(1, 104):
        raw = id2label[str(idx)]
        key = raw.strip()
        if key not in META:
            missing.append(raw)
            continue
        ru, emoji, kcal, protein, fat, carbs, fiber, sugar, density, countable, units = META[key]
        row = {
            "id": idx,
            "en": key,
            "ru": ru,
            "emoji": emoji,
            "kcal": kcal,
            "protein": protein,
            "fat": fat,
            "carbs": carbs,
            "fiber": fiber,
            "sugar": sugar,
            "g_per_cm2": density,
            "countable": countable,
        }
        if units:
            row["unit"] = list(units)
        items.append(row)
    if missing or len(items) != 104:
        raise SystemExit(f"Нет метаданных: {missing}")
    payload = {
        "plate_diameter_cm": 26,
        "per": "100g",
        "note": (
            "Ккал и БЖУ на 100 г — типичные значения USDA FoodData Central. "
            "g_per_cm2 оценивает граммы по площади маски: плотность продукта умножить на обычную толщину на тарелке. "
            "Если тарелка не упирается в края кадра, её диаметр принимается около 26 см."
        ),
        "items": items,
    }
    out = os.path.join(ROOT, "data", "ingredients.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print("wrote", out, "classes", 103)


if __name__ == "__main__":
    main()
